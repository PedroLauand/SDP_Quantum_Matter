"""Readable level-3 complex robustness SDP.

This file is meant to read like the mathematical SDP itself.

All low-level sparse-coordinate and SCS plumbing lives in
``level3_scs_backend.py``. What remains here is the formulation:

1. declare the scalar ``t`` and the matrix variables ``tau``, ``gamma``,
   ``sigma``
2. declare the PPT auxiliary matrices
3. impose the trace-one constraints
4. impose the internal symmetry constraints
5. impose the observed ``ABC`` anchor on ``sigma``
6. impose the cross-inflation marginal equalities
7. impose the old 14-PPT family
8. impose ``t >= 0`` and PSD constraints on every matrix variable

Slot convention for every 9-party matrix:

    (A1, B1, C1, A2, B2, C2, A3, B3, C3)

Inflated variables:

- ``tau``   : three disconnected triangle copies
- ``gamma`` : one triangle copy plus one disconnected 6-ring
- ``sigma`` : one connected 9-ring
"""

